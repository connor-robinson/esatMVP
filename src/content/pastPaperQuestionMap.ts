/** Per-year totals, derived so the published counts cannot drift from the data. */
export const QUESTION_MAP_SUMMARY = (() => {
  const years = new Map<
    number,
    { year: number; verified: number; likely: number; total: number }
  >();

  for (const entry of PAST_PAPER_QUESTION_MAP) {
    if (entry.relevanceStatus !== "duplicate") continue;
    const row =
      years.get(entry.year) ??
      { year: entry.year, verified: 0, likely: 0, total: 0 };
    if (entry.mappingStatus === "verified") row.verified += 1;
    if (entry.mappingStatus === "likely") row.likely += 1;
    row.total += 1;
    years.set(entry.year, row);
  }

  return Array.from(years.values()).sort((a, b) => b.year - a.year);
})();

export const DUPLICATE_TOTALS = {
  verified: QUESTION_MAP_SUMMARY.reduce((sum, row) => sum + row.verified, 0),
  likely: QUESTION_MAP_SUMMARY.reduce((sum, row) => sum + row.likely, 0),
  get total() {
    return this.verified + this.likely;
  },
  years: QUESTION_MAP_SUMMARY.length,
};

export function questionsForYear(year: number): readonly PastPaperQuestion[] {
  return PAST_PAPER_QUESTION_MAP.filter((entry) => entry.year === year);
}

export function duplicatesToSkip(): readonly PastPaperQuestion[] {
  return PAST_PAPER_QUESTION_MAP.filter(
    (entry) => entry.relevanceStatus === "duplicate",
  );
}
